// Pruebas (sin internet ni navegador) del trabajo SIN conexión: fusión de cuentas, bandeja de pendientes, superposición y copia local.
// npm run sinconexion:probar
import { fusionar, iguales } from "../src/sinConexion/fusion.js";
import { crearBandeja } from "../src/sinConexion/bandeja.js";
import { aplicarPendientes } from "../src/sinConexion/superposicion.js";
import { almacenMemoria } from "../src/sinConexion/almacen.js";
import { crearEspejo } from "../src/sinConexion/espejo.js";
import { describirConflicto } from "../src/sinConexion/textos.js";

let total = 0, fallas = 0;
const ok = (c, t) => { total++; if (!c) fallas++; console.log(`${c ? "✔" : "✘"} ${t}`); };
const pago = (id, monto, extra = {}) => ({ id, ts: 1, metodoPago: "efectivo", monto, ...extra });
const cuenta = (extra = {}) => ({ id: "c1", mesa: "5", ts: 1, estado: "abierta", pagos: [], personas: 2, ...extra });

console.log("── Fusión: lo hecho sin internet + lo que pasó en el servidor ──");
let f = fusionar(cuenta(), cuenta({ personas: 4 }), cuenta());
ok(f.aplicable && f.valor.personas === 4 && f.conflictos.length === 0, "solo cambió este dispositivo → queda lo local");
f = fusionar(cuenta(), cuenta(), cuenta({ personas: 6 }));
ok(f.aplicable && f.valor.personas === 6, "solo cambió el servidor → queda lo del servidor");
f = fusionar(cuenta(), cuenta({ personas: 4 }), cuenta({ mesa: "7" }));
ok(f.aplicable && f.valor.personas === 4 && f.valor.mesa === "7" && f.conflictos.length === 0, "cambiaron campos distintos → se unen los dos cambios");
f = fusionar(cuenta(), cuenta({ personas: 4 }), cuenta({ personas: 6 }));
ok(f.aplicable && f.valor.personas === 6 && f.conflictos.length === 1 && f.conflictos[0].campo === "personas" && !f.conflictos[0].grave, "cambiaron el MISMO campo → gana el servidor y queda anotado");
f = fusionar(cuenta(), cuenta({ pagos: [pago("a", 5000)] }), cuenta({ pagos: [pago("b", 7000)] }));
ok(f.aplicable && f.valor.pagos.map((p) => p.id).sort().join() === "a,b", "dos dispositivos registraron pagos distintos → se conservan los dos, sin repetir");
f = fusionar(cuenta({ pagos: [pago("a", 5000)] }), cuenta({ pagos: [pago("a", 5000), pago("c", 1000)] }), cuenta({ pagos: [pago("a", 5000), pago("b", 7000)] }));
ok(f.aplicable && f.valor.pagos.length === 3, "un pago que ya estaba en la base no se duplica al unir");
f = fusionar(cuenta(), cuenta({ pagos: [pago("a", 5000)] }), cuenta({ estado: "pagada", pagos: [pago("z", 12000)] }));
ok(!f.aplicable && f.conflictos.some((c) => c.grave && c.motivo === "cuenta-cerrada-en-otro-dispositivo"), "GRAVE: aquí se cobró y desde otro dispositivo la cuenta ya se cerró → NO se aplica (evita cobrar dos veces)");
f = fusionar(cuenta(), cuenta({ estado: "cancelada" }), cuenta({ estado: "pagada", pagos: [pago("z", 12000)] }));
ok(f.aplicable && f.valor.estado === "pagada" && f.conflictos.some((c) => c.campo === "estado" && !c.grave), "cancelar aquí vs pagar allá (sin pagos nuevos aquí): gana el servidor y queda anotado");
f = fusionar(null, cuenta({ id: "n1" }), null);
ok(f.aplicable && f.valor.id === "n1", "cuenta creada sin internet: se sube tal cual");
f = fusionar(null, cuenta({ id: "n1" }), cuenta({ id: "n1" }));
ok(f.aplicable, "reenviar algo que ya se había subido no genera conflicto");
f = fusionar(null, cuenta({ id: "n1", mesa: "1" }), cuenta({ id: "n1", mesa: "2" }));
ok(!f.aplicable && f.conflictos[0].motivo === "creado-en-ambos", "GRAVE: la misma cuenta se creó en dos dispositivos distintos → revisión humana");
f = fusionar(cuenta(), cuenta({ personas: 9 }), null);
ok(!f.aplicable && f.conflictos[0].motivo === "borrado-en-servidor", "GRAVE: el servidor la borró mientras aquí se editaba → revisión humana");
ok(iguales({ a: 1, b: [1, 2] }, { b: [1, 2], a: 1 }) && !iguales({ a: 1 }, { a: 2 }) && iguales(undefined, null), "comparar registros no depende del orden de los campos");

console.log("\n── Bandeja de cambios pendientes ──");
const almacen = almacenMemoria();
let t = 1000; const reloj = () => ++t;
let b = crearBandeja({ almacen, reloj });
await b.iniciar();
await b.encolar({ tipo: "set", ruta: "orders/o1", valor: { id: "o1", total: 1 } });
await b.encolar({ tipo: "set", ruta: "orders/o2", valor: { id: "o2", total: 2 } });
ok(b.pendientes().length === 2 && b.resumen().pendientes === 2, "guarda los cambios hechos sin internet");
let b2 = crearBandeja({ almacen, reloj }); await b2.iniciar();
ok(b2.pendientes().map((o) => o.ruta).join() === "orders/o1,orders/o2", "si se recarga o cierra la app, los pendientes siguen ahí y en el mismo orden");
await b.encolar({ tipo: "registro", ruta: "cuentas/c1", base: cuenta(), nuevo: cuenta({ personas: 3 }) });
await b.encolar({ tipo: "registro", ruta: "cuentas/c1", base: cuenta({ personas: 3 }), nuevo: cuenta({ personas: 3, pagos: [pago("a", 5)] }) });
const regs = b.pendientes().filter((o) => o.tipo === "registro");
ok(regs.length === 1 && regs[0].base.personas === 2 && regs[0].nuevo.pagos.length === 1, "varios cambios seguidos a la misma cuenta se juntan en uno (conserva la base original)");
const enviados = [];
let r = await b.drenar(async (op) => { enviados.push(op.ruta); return { ok: true }; });
ok(r.enviadas === 3 && enviados.join() === "orders/o1,orders/o2,cuentas/c1" && b.pendientes().length === 0, "al volver internet se envían todos, en el orden en que se hicieron");
const b3 = crearBandeja({ almacen: almacenMemoria(), reloj }); await b3.iniciar();
for (const n of ["x1", "x2", "x3"]) await b3.encolar({ tipo: "set", ruta: `orders/${n}`, valor: { id: n } });
const visto = [];
r = await b3.drenar(async (op) => { visto.push(op.ruta); if (op.ruta === "orders/x2") throw new Error("se cayó la red"); return { ok: true }; });
ok(r.detenido && visto.join() === "orders/x1,orders/x2" && b3.pendientes().map((o) => o.ruta).join() === "orders/x2,orders/x3", "si se cae la red a mitad de camino, se detiene y NO pierde lo que faltaba (x1 subió; x2 y x3 siguen pendientes)");
r = await b3.drenar(async () => ({ ok: true }));
ok(r.enviadas === 2 && b3.pendientes().length === 0, "en el siguiente intento termina de enviar lo que faltaba");
const b4 = crearBandeja({ almacen: almacenMemoria(), reloj }); await b4.iniciar();
await b4.encolar({ tipo: "registro", ruta: "cuentas/c9", base: cuenta(), nuevo: cuenta({ personas: 1 }) });
await b4.encolar({ tipo: "set", ruta: "orders/y1", valor: { id: "y1" } });
r = await b4.drenar(async (op) => (op.tipo === "registro" ? { conflicto: { motivo: "cuenta-cerrada-en-otro-dispositivo" } } : { ok: true }));
ok(r.conflictos === 1 && b4.conflictos().length === 1 && b4.pendientes().length === 0, "un choque grave se aparta para revisión y los demás cambios siguen su camino");
await b4.reintentarConflicto(b4.conflictos()[0].id);
ok(b4.pendientes().length === 1 && b4.conflictos().length === 0, "«reintentar» devuelve el cambio a la bandeja");
await b4.drenar(async () => ({ conflicto: { motivo: "x" } }));
await b4.descartarConflicto(b4.conflictos()[0].id);
ok(b4.conflictos().length === 0, "«descartar» lo elimina");
let lanzados = 0; const b5 = crearBandeja({ almacen: almacenMemoria(), reloj }); await b5.iniciar(); await b5.encolar({ tipo: "set", ruta: "orders/z", valor: { id: "z" } });
const lento = b5.drenar(async () => { lanzados++; await new Promise((x) => setTimeout(x, 30)); return { ok: true }; });
const otro = await b5.drenar(async () => { lanzados++; return { ok: true }; });
await lento;
ok(otro.ocupada && lanzados === 1, "nunca corren dos envíos a la vez (no se manda dos veces el mismo cambio)");
let avisos = 0; const b6 = crearBandeja({ almacen: almacenMemoria(), reloj }); await b6.iniciar(); b6.alCambiar(() => { avisos++; });
await b6.encolar({ tipo: "set", ruta: "orders/w", valor: { id: "w" } });
ok(avisos >= 1 && b6.resumen().pendientes === 1, "la pantalla se entera cuando cambia el número de pendientes");

console.log("\n── Superposición: ver el trabajo pendiente encima de lo último del servidor ──");
const servidor = [{ id: "o1", estado: "listo" }, { id: "o2", estado: "pendiente" }];
let v = aplicarPendientes([{ tipo: "set", ruta: "orders/o3", valor: { id: "o3", estado: "pendiente" } }], "orders", servidor);
ok(v.length === 3 && v.some((x) => x.id === "o3"), "un pedido tomado sin internet aparece en la lista");
v = aplicarPendientes([{ tipo: "mezclar", ruta: "orders/o2", parche: { estado: "listo" } }], "orders", servidor);
ok(v.find((x) => x.id === "o2").estado === "listo" && v.find((x) => x.id === "o1").estado === "listo", "un cambio de estado pendiente se ve aplicado");
v = aplicarPendientes([{ tipo: "borrar", ruta: "orders/o1" }], "orders", servidor);
ok(v.length === 1 && v[0].id === "o2", "un borrado pendiente quita el registro de la lista");
v = aplicarPendientes([{ tipo: "registro", ruta: "cuentas/c1", base: cuenta(), nuevo: cuenta({ estado: "pagada" }) }], "cuentas", [cuenta()]);
ok(v.length === 1 && v[0].estado === "pagada", "una cuenta cobrada sin internet se ve como cobrada");
v = aplicarPendientes([{ tipo: "registro", ruta: "cuentas/c1", base: cuenta(), nuevo: cuenta({ estado: "pagada" }) }], "orders", servidor);
ok(v.length === 2, "los cambios de otras colecciones no se mezclan");
v = aplicarPendientes([{ tipo: "pedidoStock", pedido: { id: "o9" }, deltas: { i1: -3 } }], "inventario", [{ id: "i1", stock: 10 }]);
ok(v[0].stock === 7, "el descuento de inventario de un pedido pendiente se refleja (10 − 3 = 7)");
v = aplicarPendientes([{ tipo: "pedidoStock", pedido: { id: "o9", estado: "pendiente" }, deltas: {} }], "orders", servidor);
ok(v.length === 3, "un pedido guardado junto con su inventario aparece en pedidos");
v = aplicarPendientes([{ tipo: "incremento", ruta: "inventario/i1/stock", delta: 5 }], "inventario", [{ id: "i1", stock: 1 }]);
ok(v[0].stock === 6, "una entrada de inventario pendiente suma al stock");

console.log("\n── Copia local ──");
const alm = almacenMemoria(); let reloj2 = 5000;
const e = crearEspejo({ almacen: alm, demoraMs: 10, reloj: () => reloj2 });
e.guardar("col:menu", [{ id: 1 }]); e.guardar("col:menu", [{ id: 1 }, { id: 2 }]);
ok((await e.leer("col:menu")) === undefined, "la copia se escribe con una pequeña espera (no en cada cambio)");
await new Promise((x) => setTimeout(x, 40));
const c = await e.leer("col:menu");
ok(c && c.valor.length === 2 && c.ts === 5000, "queda solo la última versión, con su fecha");
e.guardar("col:mesas", [1]); await e.volcarTodo();
ok(!!(await e.leer("col:mesas")), "al cerrar la pestaña se puede escribir de inmediato lo que estaba esperando");
await alm.guardar("op:1", { id: "x" });
await e.vaciar();
ok((await e.leer("col:menu")) === undefined && (await alm.leer("op:1")) !== undefined, "al cerrar sesión se borra la copia de datos pero NO los cambios pendientes por enviar");

console.log("\n── Textos de los choques ──");
const d1 = describirConflicto({ tipo: "registro", ruta: "cuentas/c1", base: cuenta(), nuevo: cuenta({ pagos: [pago("a", 25000), pago("b", 5000)] }), detalle: { motivo: "cuenta-cerrada-en-otro-dispositivo" } });
ok(d1.titulo === "Cuenta c1" && /no cobrar dos veces/.test(d1.detalle) && /\$30\.000/.test(d1.detalle.replace(/\s/g, "")), "un cobro que chocó dice qué cuenta es, por qué no se aplicó y cuánto se cobró sin sincronizar ($30.000)");
const d2 = describirConflicto({ tipo: "pedidoStock", pedido: { id: "ordenMuyLarga123456789" }, detalle: { motivo: "sin-permiso" } });
ok(d2.titulo.startsWith("Pedido …") && /no tiene permiso/.test(d2.detalle), "un pedido sin permiso muestra el id corto y el motivo en palabras");
ok(/no se pudo guardar/i.test(describirConflicto({ tipo: "set", ruta: "turnos/t1", detalle: { motivo: "raro" } }).detalle), "un motivo desconocido igual tiene un texto claro");

console.log(`\n${total - fallas}/${total} pruebas correctas.`);
if (fallas > 0) { console.error(`✘ ${fallas} prueba(s) fallaron`); process.exit(1); }
